public class letter {
    public static void main(String[] args) {
        String word = "Hello world"; // Given word

        // Check if the word has at least 2 letters
        if (word.length() >= 0) {
            System.out.println(word.charAt(10)); // Print 2nd letter (index 1)
        } else {
            System.out.println("Word is too short.");
        }
    }
}
 
    

